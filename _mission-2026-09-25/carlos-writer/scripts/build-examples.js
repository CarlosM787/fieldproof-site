'use strict';
/*
 * Builds the real-example check from five public passages of carlosmoralesjr.com
 * (carlosmoralesjr-site@fc65513), using the extension's own prompt builder, so the
 * prompts shown are exactly what the extension sends.
 *
 * Writes:
 *   examples/REAL_EXAMPLES.md            exact prompts with the shipped neutral guide (public)
 *   scripts/selftest-requests.json       request bodies for scripts/selftest.ps1 (neutral guide)
 *   private/REAL_EXAMPLES_PROMPTS_CARLOS.md and private/selftest-requests-carlos.json
 *                                        the same with Carlos's guide (if private/carlos-style-guide.json exists)
 * Run: node scripts/build-examples.js
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const P = require('../extension/lib/prompts.js');

const ROOT = path.resolve(__dirname, '..');
const SITE = '/home/user/carlosmoralesjr-site';
const REF = 'fc65513';
const git = (f) => execFileSync('git', ['-C', SITE, 'show', REF + ':' + f]).toString();
const templates = git('src/templates.mjs');
const projects = git('content/projects.mjs');

// Plain text of a template string: drop tags and ${...} link wrappers.
const plain = (s) => s.replace(/<a [^>]*>/g, '').replace(/<\/a>/g, '').replace(/\$\{[^}]*\}/g, '').replace(/\s+/g, ' ').trim();
const between = (src, start, end) => {
  const i = src.indexOf(start);
  if (i < 0) throw new Error('not found: ' + start);
  const j = src.indexOf(end, i + start.length);
  return src.slice(i + start.length, j);
};

const PASSAGES = [
  {
    id: 'home-lead',
    where: 'Home page lead, https://carlosmoralesjr.com/',
    text: plain(between(templates, '<p class="lead">I’m an electrical engineer.', '</p>').replace(/^/, 'I’m an electrical engineer.')),
  },
  {
    id: 'about-night',
    where: 'About page, second paragraph, https://carlosmoralesjr.com/about/',
    text: plain(between(templates, '<p>At night I build software.', '</p>').replace(/^/, 'At night I build software.')),
  },
  {
    id: 'salsacoach',
    where: 'Projects page, SalsaCoach, https://carlosmoralesjr.com/projects/',
    text: (() => {
      const blk = between(projects, "slug: 'salsacoach',", 'links:');
      const line = between(blk, "line: '", "',");
      const status = between(blk, "status: '", "',");
      return line + ' ' + status;
    })(),
  },
  {
    id: 'talkestimate',
    where: 'Projects page, TalkEstimate, https://carlosmoralesjr.com/projects/',
    text: (() => {
      const blk = between(projects, "slug: 'talkestimate',", 'links:');
      const line = between(blk, "line: '", "',");
      const status = between(blk, "status: '", "',");
      return line + ' ' + status;
    })(),
  },
  {
    id: 'subscribe-get',
    where: 'Subscribe page, "What you’ll get", https://carlosmoralesjr.com/subscribe/',
    text: plain(between(templates, '<h2>What you’ll get</h2>\n      <p>', '</p>')),
  },
];

const ACTIONS = ['proofread', 'carlos', 'casual', 'professional', 'en2es'];

function build(settings, label) {
  const requests = [];
  for (const p of PASSAGES) {
    for (const a of ACTIONS) {
      const prompt = P.buildPrompt(a, p.text, settings);
      requests.push({ passage: p.id, action: a, body: P.buildOllamaBody(prompt, settings, { stream: false }) });
    }
    // Round trip: Spanish back to English. The selftest fills in the en2es output at run time.
    const back = P.buildPrompt('es2en', '{{EN2ES_OUTPUT}}', settings);
    const body = P.buildOllamaBody(back, settings, { stream: false });
    body.options.num_predict = Math.min(4096, Math.max(256, Math.ceil(P.estimateTokens(p.text) * 1.4 * 2.5) + 64));
    requests.push({ passage: p.id, action: 'es2en', roundTripOf: 'en2es', body });
  }
  return {
    generated: new Date().toISOString().slice(0, 10),
    note: 'Built by scripts/build-examples.js from carlosmoralesjr-site@' + REF + ' with extension/lib/prompts.js v' + P.VERSION + '. Guide: ' + label + '. The model name is replaced by selftest.ps1 -Model.',
    passages: PASSAGES,
    requests,
  };
}

function markdown(data, settings, guideLabel, isPrivate) {
  const L = [];
  L.push('# Real-example check: the exact prompts' + (isPrivate ? ' (Carlos guide)' : ''));
  L.push('');
  if (isPrivate) L.push('PRIVATE (contains the Carlos style guide). ');
  L.push('Five passages of published copy from carlosmoralesjr.com (source: `carlosmoralesjr-site@' + REF + '`), run through each action. Generated by `scripts/build-examples.js` with the extension\'s own prompt builder (`extension/lib/prompts.js` v' + P.VERSION + '), default settings, style guide: **' + guideLabel + '**.');
  L.push('');
  L.push('**No model was run here.** This container has no GPU and model downloads are blocked, so this file shows what would be sent, not what a model would answer. To see answers and timings on Carlos\'s PC, run `scripts/selftest.ps1` after installing Ollama and a model (his decision).');
  L.push('');
  L.push('Every request goes to `POST http://localhost:11434/api/chat` with `"think": false`, `"options": {"num_ctx": 8192, "top_p": 0.9, "temperature": 0.1 | 0.2 | 0.4, "num_predict": ...}`. The extension streams (`"stream": true`); the self-test uses `"stream": false` to read Ollama\'s timing fields.');
  L.push('');
  L.push('## The five passages');
  L.push('');
  data.passages.forEach((p, i) => { L.push((i + 1) + '. **' + p.id + '** (' + p.where + ')'); L.push(''); L.push('   > ' + p.text); L.push(''); });
  L.push('## System prompt per action');
  L.push('');
  L.push('The system prompt does not depend on the passage. The user message is always the passage in `<passage>` tags plus a one-line reminder.');
  L.push('');
  for (const a of ['proofread', 'carlos', 'casual', 'professional', 'en2es', 'es2en']) {
    const req = data.requests.find((r) => r.action === a);
    L.push('### ' + a + ' (temperature ' + req.body.options.temperature + ')');
    L.push('');
    L.push('```text');
    L.push(req.body.messages[0].content);
    L.push('```');
    L.push('');
  }
  L.push('## User message per passage (Proofread shown; other actions differ only in the last line)');
  L.push('');
  for (const p of data.passages) {
    const req = data.requests.find((r) => r.passage === p.id && r.action === 'proofread');
    L.push('```text');
    L.push(req.body.messages[1].content);
    L.push('```');
    L.push('');
  }
  L.push('Last lines by action: ' + ['proofread', 'carlos', 'casual', 'professional', 'en2es', 'es2en'].map((a) => a + ': "' + data.requests.find((r) => r.action === a).body.messages[1].content.split('\n').pop() + '"').join('; ') + '.');
  L.push('');
  L.push('## Facts the checker will watch in each passage');
  L.push('');
  for (const p of data.passages) {
    const x = P.extractProtected(p.text);
    L.push('- **' + p.id + '**: numbers ' + JSON.stringify(x.numbers) + ', names ' + JSON.stringify(x.names) + (x.urls.length ? ', links ' + JSON.stringify(x.urls) : '') + (x.emails.length ? ', emails ' + JSON.stringify(x.emails) : ''));
  }
  L.push('');
  return L.join('\n');
}

const neutral = P.mergeSettings({});
const pub = build(neutral, 'Neutral default');
fs.mkdirSync(path.join(ROOT, 'examples'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'scripts', 'selftest-requests.json'), JSON.stringify(pub, null, 2) + '\n');
fs.writeFileSync(path.join(ROOT, 'examples', 'REAL_EXAMPLES.md'), markdown(pub, neutral, 'Neutral default (shipped)', false));

const carlosFile = path.join(ROOT, 'private', 'carlos-style-guide.json');
if (fs.existsSync(carlosFile)) {
  const g = JSON.parse(fs.readFileSync(carlosFile, 'utf8'));
  const s = P.mergeSettings(Object.assign({}, g.settings, { styleGuide: g.styleGuide, styleGuideName: g.styleGuideName }));
  const priv = build(s, g.styleGuideName);
  fs.writeFileSync(path.join(ROOT, 'private', 'selftest-requests-carlos.json'), JSON.stringify(priv, null, 2) + '\n');
  fs.writeFileSync(path.join(ROOT, 'private', 'REAL_EXAMPLES_PROMPTS_CARLOS.md'), markdown(priv, s, g.styleGuideName, true));
}
console.log('passages:', PASSAGES.map((p) => p.id + ' (' + p.text.split(/\s+/).length + ' words)').join(', '));
console.log('requests:', pub.requests.length);
