'use strict';
// Writes ahk/prompts.txt from the extension's prompt builder, so the optional AutoHotkey
// route sends the same prompts as the extension (default settings). Run: node scripts/build-ahk-prompts.js
const fs = require('fs');
const path = require('path');
const P = require('../extension/lib/prompts.js');
const s = P.mergeSettings({ styleGuide: '{{STYLE_GUIDE}}' });
const out = ['# Generated by scripts/build-ahk-prompts.js from extension/lib/prompts.js v' + P.VERSION + '. Do not edit by hand.',
  '# Placeholders: {{STYLE_GUIDE}} (text of style-guide.txt) and {{TEXT}} (your selection).'];
for (const a of P.ACTIONS) {
  const p = P.buildPrompt(a.id, '{{TEXT}}', s);
  out.push('=== ' + a.id + ' | ' + a.label + ' | temperature=' + p.temperature);
  out.push('--- system');
  out.push(p.system);
  out.push('--- user');
  out.push(p.user);
}
out.push('=== end');
fs.writeFileSync(path.join(__dirname, '..', 'ahk', 'prompts.txt'), out.join('\n') + '\n');
console.log('ahk/prompts.txt written,', P.ACTIONS.length, 'actions');
